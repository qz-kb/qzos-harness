/** QZOS synthetic flows inside the shipped Web composition. */
import { fileURLToPath } from 'node:url'
import { mkdir, readFile } from 'node:fs/promises'
import { chromium } from 'playwright'
import { expect, it } from 'vitest'
import { launchWebScaffold, seedSession, watchConsole } from './scaffold.ts'

it('browses QZOS catalogs with native employee conversations and no duplicate workbench', async () => {
  const scaffold = await launchWebScaffold({ extraOverlayPath: fileURLToPath(new URL('./pin-browse-picker.overlay.yml', import.meta.url)) })
  try {
    await seedSession(scaffold, await readFile(new URL('../../../snapshots/web/seeded-history/session.v3.jsonl', import.meta.url), 'utf8'), 'qzos-native-window')
    const browser = await chromium.launch()
    try {
      const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' })
      const console = watchConsole(page)
      await page.addInitScript(() => { window.sessionStorage.setItem('qzos.preview', '1') })
      await page.goto(scaffold.authenticatedUrl)
      const panel = page.locator('[data-qzos-panel]')
      const navigate = async (name: string) => { await page.getByRole('navigation').getByRole('button', { name, exact: true }).click() }
      const native = page.getByRole('navigation').getByRole('button', { name: '工作窗口', exact: true })
      await native.waitFor()
      expect(await native.getAttribute('aria-current')).toBe('page')
      expect(await panel.count()).toBe(0)
      await page.locator('[role="treeitem"]').first().click()
      await page.locator('[role="treeitem"]').nth(1).click()
      const nativeInput = page.locator('[data-composer-input][contenteditable="true"]').first()
      await page.getByText('DONE', { exact: true }).waitFor()
      await nativeInput.fill('原始工作窗口的未发送草稿')
      await expect.poll(() => nativeInput.innerText()).toContain('原始工作窗口的未发送草稿')
      await navigate('知识库')
      await navigate('工作窗口')
      await expect.poll(() => nativeInput.innerText()).toContain('原始工作窗口的未发送草稿')
      if (process.env.QZOS_UI_SCREENSHOTS) {
        await mkdir(process.env.QZOS_UI_SCREENSHOTS, { recursive: true })
        await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-native-window.png` })
      }
      const labels = await page.getByRole('navigation').getByRole('button').allTextContents()
      expect(labels.slice(0, 6)).toMatchInlineSnapshot(`
        [
          "工作窗口",
          "知识库",
          "数字员工",
          "连接器",
          "技能",
          "模板",
        ]
      `)
      expect(labels).not.toContain('工作台')
      expect(labels).not.toContain('成果')
      await navigate('知识库')
      await panel.getByRole('button', { name: '共享给我的', exact: true }).click()
      await panel.getByRole('button', { name: '查看详情 · 产品与客户洞察', exact: true }).waitFor()
      expect(await panel.getByRole('button', { name: /^编辑 ·/ }).count()).toBe(0)
      await panel.getByRole('button', { name: '我的', exact: true }).click()
      if (process.env.QZOS_UI_SCREENSHOTS) await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-knowledge.png` })
      await panel.getByRole('button', { name: '新增知识库', exact: true }).click()
      const configuration = page.getByRole('dialog', { name: '新增知识库', exact: true })
      await configuration.getByRole('textbox', { name: '知识库名称' }).fill('界面演示知识库')
      await configuration.getByRole('textbox', { name: '知识库简介' }).fill('本轮只验证界面')
      expect(await configuration.getByRole('combobox').count()).toBe(2)
      await configuration.getByRole('button', { name: '保存', exact: true }).click()
      const previewCard = panel.locator('article').filter({ hasText: '界面演示知识库' })
      await previewCard.hover()
      await previewCard.getByRole('button', { name: '编辑 · 界面演示知识库', exact: true }).click()
      const editing = page.getByRole('dialog', { name: '编辑知识库', exact: true })
      expect(await editing.getByRole('combobox').first().isDisabled()).toBe(true)
      await editing.getByRole('textbox', { name: '知识库简介' }).fill('修改后的简介')
      await editing.getByRole('button', { name: '保存', exact: true }).click()
      await previewCard.getByText('修改后的简介', { exact: true }).waitFor()
      await previewCard.hover()
      await previewCard.getByRole('button', { name: '删除 · 界面演示知识库', exact: true }).click()
      await page.getByRole('dialog', { name: '确认删除？', exact: true }).getByRole('button', { name: '取消', exact: true }).click()
      expect(await previewCard.count()).toBe(1)
      await previewCard.hover()
      await previewCard.getByRole('button', { name: '删除 · 界面演示知识库', exact: true }).click()
      await page.getByRole('dialog', { name: '确认删除？', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
      expect(await previewCard.count()).toBe(0)
      await panel.getByRole('button', { name: '查看详情 · 团队知识库', exact: true }).click()
      await panel.getByRole('button', { name: '手动录入', exact: true }).click()
      await panel.getByRole('button', { name: '录入数据', exact: true }).click()
      const fragment = page.getByRole('dialog', { name: '录入数据', exact: true })
      await fragment.getByRole('textbox', { name: '文档内容', exact: true }).fill('模拟新增的知识内容')
      await fragment.getByRole('button', { name: '确认', exact: true }).click()
      await panel.getByText('模拟新增的知识内容', { exact: true }).waitFor()
      await panel.getByRole('button', { name: '搜索测试', exact: true }).click()
      await panel.getByRole('textbox', { name: '测试文本', exact: true }).fill('入职事项')
      await panel.getByRole('button', { name: '测试', exact: true }).click()
      await panel.getByText('以下为演示检索结果，未进行真实检索。', { exact: true }).waitFor()
      await panel.getByRole('button', { name: '团队成员', exact: true }).click()
      await panel.getByRole('button', { name: '+ 添加成员', exact: true }).click()
      const member = page.getByRole('dialog', { name: '添加成员', exact: true })
      await member.getByRole('textbox', { name: '搜索成员', exact: true }).fill('测试成员')
      await member.getByRole('button', { name: '确认', exact: true }).click()
      await panel.getByRole('cell', { name: '测试成员', exact: true }).waitFor()
      await panel.getByRole('button', { name: '知识库设置', exact: true }).click()
      await panel.getByRole('textbox', { name: '简介', exact: true }).fill('设置保存后的简介')
      await panel.getByRole('button', { name: '保存设置', exact: true }).click()
      if (process.env.QZOS_UI_SCREENSHOTS) await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-knowledge-settings.png` })
      await navigate('数字员工')
      await panel.getByRole('combobox', { name: '适用范围', exact: true }).selectOption('public')
      expect(await panel.getByRole('button', { name: '开始对话 · 知识助手', exact: true }).count()).toBe(0)
      await panel.getByRole('combobox', { name: '适用范围', exact: true }).selectOption('all')
      await panel.getByRole('button', { name: '创建数字员工', exact: true }).click()
      const employeeCreation = page.getByRole('dialog', { name: '新建数字员工', exact: true })
      await employeeCreation.getByRole('textbox', { name: '名称', exact: true }).fill('演示新员工')
      await employeeCreation.getByRole('textbox', { name: '职责描述', exact: true }).fill('按原交互展示本地示例')
      await employeeCreation.getByRole('button', { name: '创建并配置', exact: true }).click()
      await panel.getByRole('button', { name: 'AI模型/搜索配置', exact: true }).click()
      await panel.getByRole('group', { name: '空搜索回复', exact: true }).getByLabel('自定义回复', { exact: true }).check()
      await panel.getByRole('textbox', { name: '回复内容', exact: true }).fill('未找到资料时的演示回复')
      await panel.getByRole('button', { name: '界面配置', exact: true }).click()
      await panel.getByRole('button', { name: '+ 添加菜单', exact: true }).click()
      const menu = page.getByRole('dialog', { name: '添加菜单', exact: true })
      await menu.getByRole('textbox', { name: '关键词', exact: true }).fill('入职')
      await menu.getByRole('textbox', { name: '回复内容', exact: true }).fill('演示菜单内容')
      await menu.getByRole('button', { name: '确认', exact: true }).click()
      await panel.getByRole('cell', { name: '入职', exact: true }).waitFor()
      await panel.getByRole('button', { name: '保存', exact: true }).click()
      await panel.getByRole('button', { name: '开始对话 · 演示新员工', exact: true }).click()
      await expect.poll(() => nativeInput.innerText()).toContain('@演示新员工')
      expect(await nativeInput.innerText()).toContain('原始工作窗口的未发送草稿')
      await navigate('数字员工')
      await panel.getByRole('button', { name: '数字员工设置 · 内容编辑', exact: true }).click()
      if (process.env.QZOS_UI_SCREENSHOTS) await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-employee-settings.png` })
      await panel.getByRole('button', { name: '发布 AI 员工', exact: true }).click()
      await panel.getByRole('button', { name: /^网页/ }).click()
      await panel.getByRole('button', { name: '创建链接', exact: true }).click()
      const share = page.getByRole('dialog', { name: '创建链接', exact: true })
      await share.getByRole('textbox', { name: '名称', exact: true }).fill('演示分享')
      await share.getByRole('button', { name: '确认', exact: true }).click()
      await panel.getByRole('cell', { name: '演示分享', exact: true }).waitFor()
      await panel.getByRole('button', { name: '立即对话', exact: true }).click()
      await expect.poll(() => nativeInput.innerText()).toContain('@内容编辑')
      await nativeInput.fill('@知')
      await page.getByRole('option', { name: /知识助手/ }).click()
      await expect.poll(() => nativeInput.innerText()).toContain('@知识助手')
      for (const [name, title, action] of [
        ['连接器', 'GitHub', '授权连接暂未开放'],
        ['技能', '文档写作', '安装与执行暂未开放'],
        ['模板', '一周工作总结', '使用模板暂未开放'],
      ] as const) {
        await navigate(name)
        await panel.getByRole('button', { name: `查看详情 · ${title}`, exact: true }).click()
        expect(await panel.getByRole('button', { name: action, exact: true }).isDisabled()).toBe(true)
        await panel.getByRole('button', { name: '返回列表', exact: true }).click()
        if (process.env.QZOS_UI_SCREENSHOTS) await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-${name}.png` })
      }
      await navigate('数字员工')
      await panel.getByRole('button', { name: '返回列表', exact: true }).click()
      await panel.getByRole('combobox', { name: '适用范围', exact: true }).selectOption('all')
      if (process.env.QZOS_UI_SCREENSHOTS) await page.screenshot({ path: `${process.env.QZOS_UI_SCREENSHOTS}/qzos-employees.png` })
      await page.setViewportSize({ width: 520, height: 850 })
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
      expect(console.pageErrors).toEqual([])
      expect(console.warnings).toEqual([])
      // Removing the contribution restores the upstream surface without fake Sessions.
      const entry = [...scaffold.ctx.loader.entries()].find(item => item.options.name === '@deepseek-ai/dsh-client-ui-qzos')
      expect(entry).toBeDefined()
      entry!.parent.tree.remove(entry!.options.id)
      await panel.waitFor({ state: 'detached' })
      expect(await page.getByRole('navigation').getByRole('button', { name: '知识库', exact: true }).count()).toBe(0)
      await scaffold.ctx.loader.create({ name: '@deepseek-ai/dsh-client-ui-qzos' })
      await navigate('知识库')
      await page.locator('[data-qzos-panel="knowledge"]').waitFor()
      await panel.getByRole('button', { name: '新增知识库', exact: true }).waitFor()
    } finally { await browser.close() }
  } finally { await scaffold.close() }
})
